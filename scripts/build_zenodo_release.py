def main() -> int:
    RELEASE_DIR.mkdir(exist_ok=True)
    files = tracked_files(TAG)
    print(f"Tag {TAG!r} has {len(files)} tracked files at HEAD of v1.0-prep.")

    write_source_zip(
        files,
        RELEASE_DIR / "d1-benchmark-v1.0-source.zip",
    )
    write_subset_zip(
        files,
        RELEASE_DIR / "d1-benchmark-v1.0-splits.zip",
        "data/processed/splits/",
        SPLITS_README,
    )
    write_subset_zip(
        files,
        RELEASE_DIR / "d1-benchmark-v1.0-results.zip",
        "results/tables/",
        RESULTS_README,
    )
    # also add figures/ into the results zip (overwrite with a second pass)
    out = RELEASE_DIR / "d1-benchmark-v1.0-results.zip"
    with zipfile.ZipFile(out, "a", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for rel in files:
            if rel.startswith("figures/") and (REPO / rel).is_file():
                zf.write(REPO / rel, PREFIX + rel)
    print(f"  + figures added to results zip")

    print()
    print("Done. Files written to:")
    for p in sorted(RELEASE_DIR.glob("d1-benchmark-v1.0-*.zip")):
        print(f"  {p}  ({p.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
