#!/usr/bin/env python3
"""Build the three Zenodo release zip files for the D1 benchmark v1.0.

Source zip      = full repo at v1.0-prep tag, minus data/raw,
                  data/cache, data/processed/networks (regenerated by build
                  scripts), data/processed/rewired (regenerated), and any
                  *.pyc / __pycache__ noise.
Splits zip      = data/processed/splits/ only + a README that points back
                  to the public release protocol section that defines
                  the 50-fold structure.
Results zip     = results/tables/ + figures/ + a README that lists what
                  each table / figure corresponds to.

Output location: <repo>/release/d1-benchmark-v1.0-*.zip
"""

from __future__ import annotations

import subprocess
import sys
import zipfile
from pathlib import Path
from typing import Iterable

REPO = Path(__file__).resolve().parent.parent
TAG = "v1.0-prep"
PREFIX = "d1-benchmark-v1.0/"   # top-level folder inside each zip
RELEASE_DIR = REPO / "release"

EXCLUDE_PREFIXES = (
    "data/raw/",
    "data/cache/",
    "data/processed/networks/",
    "data/processed/rewired/",
)

# Paths we only want in the source zip (not in splits/results zips).
SOURCE_ONLY_NOTE = (
    "Note: data/processed/networks/ is excluded because the user rebuilds "
    "it from data/raw/ + scripts/build_*.py. The splits inside this zip are "
    "the canonical 50-fold (5-fold x 10-repeat) StratifiedKFold outputs at "
    "seed 20260926 + r, committed at v1.0-prep tag.\n"
)


def tracked_files(tag: str) -> list[str]:
    out = subprocess.check_output(
        ["git", "ls-tree", "-r", "--name-only", tag],
        cwd=str(REPO),
        text=True,
    )
    return [ln.strip().replace("\\", "/") for ln in out.splitlines() if ln.strip()]


def write_source_zip(files: list[str], out_path: Path) -> None:
    excluded = 0
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for rel in files:
            if any(rel.startswith(p) for p in EXCLUDE_PREFIXES):
                excluded += 1
                continue
            src = REPO / rel
            if not src.is_file():
                continue
            arcname = PREFIX + rel
            zf.write(src, arcname)
    print(f"  source  zip: {out_path}  ({out_path.stat().st_size / 1e6:.1f} MB, "
          f"{len(files) - excluded} files, {excluded} excluded)")


def write_subset_zip(
    files: list[str],
    out_path: Path,
    keep_prefix: str,
    readme_text: str,
) -> None:
    kept: list[str] = []
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for rel in files:
            if not rel.startswith(keep_prefix):
                continue
            src = REPO / rel
            if not src.is_file():
                continue
            zf.write(src, PREFIX + rel)
            kept.append(rel)
        zf.writestr(PREFIX + "README_zenodo_subset.txt", readme_text)
    print(f"  subset  zip: {out_path}  ({out_path.stat().st_size / 1e6:.1f} MB, "
          f"{len(kept)} files)")


